//! 构建脚本：扫描 `web/`，把前端资源编进二进制的清单。
//!
//! 手写 `include_str!` 列表的代价是「新增文件忘了注册」—— 表现为线上 404，
//! 而且只有点开对应页面才会发现。这里改成构建期扫描：新增即生效，
//! 顺带算出内容指纹供 ETag 使用，并在 `cargo:rerun-if-changed` 上挂好目录，
//! 改一个字节就会触发重编。

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, io};

/// 前端资源根目录，相对包根。
const WEB_DIR: &str = "web";

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let web_dir = manifest_dir.join(WEB_DIR);

    // 目录级别监听：新增/删除文件同样会触发重建
    println!("cargo:rerun-if-changed={WEB_DIR}");
    println!("cargo:rerun-if-changed=build.rs");

    let files = collect(&web_dir).unwrap_or_else(|err| {
        panic!(
            "failed to scan {}: {err}。前端资源目录必须存在，否则页面会全部 404",
            web_dir.display()
        )
    });

    for required in ["index.html", "admin.html", "interstitial.html"] {
        assert!(
            files.iter().any(|file| file.relative == required),
            "缺少 {WEB_DIR}/{required}，页面无法渲染"
        );
    }

    let mut source = String::with_capacity(files.len() * 120);
    source.push_str("// @generated by build.rs, do not edit.\n\n");
    source.push_str("/// 资源路径（相对 web/）与内容。\n");
    source.push_str("pub(crate) static EMBEDDED: &[(&str, &[u8])] = &[\n");

    let mut stamp = Fnv::new();
    for file in &files {
        // 内容指纹覆盖路径与字节，改内容或重命名都会变
        stamp.write(file.relative.as_bytes());
        stamp.write(&file.bytes);

        writeln!(
            source,
            "    ({:?}, include_bytes!({:?})),",
            file.relative,
            file.absolute.to_string_lossy().replace('\\', "/")
        )
        .expect("write to String never fails");
    }
    source.push_str("];\n\n");
    writeln!(
        source,
        "/// 本次构建的资源指纹，用于 ETag 与启动日志。\npub(crate) const ASSET_STAMP: &str = \"{:016x}\";",
        stamp.finish()
    )
    .expect("write to String never fails");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("assets_manifest.rs");
    fs::write(&out, source).unwrap_or_else(|err| {
        panic!("failed to write {}: {err}", out.display());
    });
}

struct AssetFile {
    /// 相对 `web/`，统一用正斜杠，作为 URL 与缓存键
    relative: String,
    absolute: PathBuf,
    bytes: Vec<u8>,
}

fn collect(root: &Path) -> io::Result<Vec<AssetFile>> {
    let mut files = Vec::new();
    walk(root, root, &mut files)?;
    files.sort_by(|left, right| left.relative.cmp(&right.relative));
    Ok(files)
}

fn walk(root: &Path, dir: &Path, files: &mut Vec<AssetFile>) -> io::Result<()> {
    let mut entries: Vec<_> = fs::read_dir(dir)?.collect::<Result<_, _>>()?;
    entries.sort_by_key(|entry| entry.file_name());

    for entry in entries {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();

        // 编辑器临时文件与隐藏目录不该进产物
        if name.starts_with('.') || name.ends_with('~') {
            continue;
        }

        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            walk(root, &path, files)?;
        } else if file_type.is_file() {
            let relative = path
                .strip_prefix(root)
                .expect("walk stays under root")
                .to_string_lossy()
                .replace('\\', "/");
            files.push(AssetFile {
                relative,
                bytes: fs::read(&path)?,
                absolute: path,
            });
        }
    }

    Ok(())
}

/// FNV-1a，够用来做内容指纹，且不引入依赖。
struct Fnv(u64);

impl Fnv {
    const OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
    const PRIME: u64 = 0x0000_0100_0000_01b3;

    fn new() -> Self {
        Self(Self::OFFSET)
    }

    fn write(&mut self, bytes: &[u8]) {
        for byte in bytes {
            self.0 ^= u64::from(*byte);
            self.0 = self.0.wrapping_mul(Self::PRIME);
        }
        // 分段写入时插入分隔，避免 ("ab","c") 与 ("a","bc") 撞出同一结果
        self.0 ^= 0xff;
        self.0 = self.0.wrapping_mul(Self::PRIME);
    }

    fn finish(&self) -> u64 {
        self.0
    }
}
