//! 前端运行时配置：`GET /app-config.js`。
//!
//! 把「站点名、是否开后台、资源版本」这类前端也关心的配置从 HTML 里挪出来，
//! 部署时换一份环境变量即可，不必重新构建前端资源。

use actix_web::http::header;
use actix_web::{get, web, HttpResponse};
use serde::Serialize;

use crate::state::AppState;

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct AppConfig {
    env: &'static str,
    site_name: String,
    /// 同源部署时为空串；反代到子路径时是 `/sub` 这类前缀
    api_base: String,
    admin_enabled: bool,
    live_reload: bool,
    assets_stamp: &'static str,
}

#[get("/app-config.js")]
pub async fn app_config(state: web::Data<AppState>) -> HttpResponse {
    let config = AppConfig {
        env: state.profile.as_str(),
        site_name: state.site_name.clone(),
        api_base: state.api_base.clone(),
        admin_enabled: state.admin.is_enabled(),
        live_reload: state.assets.live_reload(),
        assets_stamp: crate::assets::ASSET_STAMP,
    };

    // 配置随时可能被环境变量改变，不能缓存
    let script = format!(
        "// generated by the server, do not edit\nwindow.__APP_CONFIG__ = {};\n",
        serde_json::to_string(&config).unwrap_or_else(|_| "{}".to_string())
    );

    HttpResponse::Ok()
        .insert_header((header::CACHE_CONTROL, "no-store"))
        .content_type("text/javascript; charset=utf-8")
        .body(script)
}
